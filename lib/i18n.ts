/**
 * Hook de traducción de UI estática. Usa el idioma global (useIdioma) y cae al
 * español si falta una clave o el idioma no está.
 */
export function useT() {
  const { idioma } = useIdioma();
  const dic = DICCIONARIOS[idioma] ?? es;
  return (clave: string): string => dic[clave] ?? es[clave] ?? clave;
}
